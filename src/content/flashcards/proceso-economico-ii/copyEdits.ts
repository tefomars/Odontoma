export function correctSpelling(text: string) {
  return text
    .replace(/\btaza de interés\b/gi, "tasa de interés")
    .replace(/\bmárgen\b/gi, "margen")
    .replace(/\bdesposita\b/g, "deposita")
    .replace(/\bimposbilita\b/g, "imposibilita")
    .replace(/\benriquezer\b/g, "enriquecer")
    .replace(/\benriquezimiento\b/g, "enriquecimiento")
    .replace(/\bprolectarios\b/gi, "proletarios")
    .replace(/\bprolectariado\b/gi, "proletariado")
    .replace(/\basosiación\b/g, "asociación")
    .replace(/\bterminos\b/g, "términos")
    .replace(/\btésis\b/g, "tesis")
    .replace(/\borigenes\b/g, "orígenes")
    .replace(/\binversiónes\b/g, "inversiones")
    .replace(/\becnomía\b/g, "economía")
    .replace(/\bKeynsesiano\b/g, "keynesiano")
    .replace(/\bKeynesiano\b/g, "keynesiano")
    .replace(/\bGreshan\b|\bGrashan\b/g, "Gresham")
    .replace(/\bFriedmann\b/g, "Friedman")
    .replace(/\bFischer\b/g, "Fisher")
    .replace(/\bdel banca central\b/g, "de la banca central")
    .replace(/\bun banca comercial\b/g, "un banco comercial")
    .replace(/^Por que\b/, "Porque")
}

export function polishCardCopy(guid: string, original: { front: string; back: string }) {
  const edit = copyEdits[guid]
  let front = correctSpelling(edit?.front ?? original.front)
    .replace(/^Porqué(?=\s)/, "Por qué")
    .replace(/^Que\b/, "Qué")
    .replace(/\?\s*(\([^?]+\)|\d+(?:\s*\+\s*[\d.]+)?)$/, " $1?")
  if (/^(?:Qué|Cuál|Cuáles|Quién|Quiénes|Cómo|Cuándo|Dónde|Por qué|En qué|En dónde|De qué|A qué|Hacia dónde|Con qué|Por medio de qué)(?=\s|$)/.test(front) && !front.includes("?")) front += "?"
  if (front.includes("?") && !front.startsWith("¿")) front = "¿" + front
  return { front, back: correctSpelling(edit?.back ?? original.back) }
}
